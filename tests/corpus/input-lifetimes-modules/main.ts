import { Entry, keep, name, normalize } from "./model.ts";
import { describe, inspect, invoke, matching, pair, read } from "./helpers.ts";
const entries = [new Entry(" Alpha ", 3), new Entry("Beta", 5)];
console.log(read(entries, 0), read(entries, 1), read(entries, 2));
console.log(matching(entries, "B"));
const records = [{ key: "Record", extra: 7 }];
