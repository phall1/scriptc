console.log(pair(records[0], records[1]));
console.log(invoke(normalize, "  INDIRECT  "));
const escaped = keep(entries[0]);
console.log(inspect(entries[0], () => { entries.length = 0; }));
console.log(name(escaped), entries.length);
const saved = name(records[0]);
records.length = 0;
console.log(saved);
